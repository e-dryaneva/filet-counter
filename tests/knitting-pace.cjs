const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'../index.html'),'utf8');
const data=new Map(),events={};
const context={Date,document:{hidden:false,addEventListener:(event,fn)=>events[event]=fn},window:{addEventListener:(event,fn)=>events[event]=fn},LS:{get:(k,fallback)=>structuredClone(data.get(k)??fallback),set:(k,v)=>data.set(k,structuredClone(v))}};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('let paceAnchor=null;'),source.indexOf('function recordKnittingActivity(')),context);
const step=context.recordKnittingPace;
assert.equal(context.knittingPace(),null,'No invented speed for old activity');
let now=Date.now()-2000000;
step('a',0,1,1,now);
for(let i=1;i<=10;i++){now+=10000;step('a',i,i+1,1,now);}
assert.equal(context.knittingPace(now),360,'10 seconds per cell');
assert.match(context.patternTimeEstimate({w:20,h:20,pos:40},360),/^Предварительно .+ — .+ осталось$/,'Estimate is a range while history is limited');
assert.equal(context.patternTimeEstimate({w:10,h:10,pos:100},null),'Схема завершена');
const count=()=>data.get('filet.pace.v1').length;
now+=360000;step('a',11,12,1,now);assert.equal(count(),10,'Long pause excluded');
now+=100;step('a',12,13,1,now);assert.equal(count(),10,'Double tap excluded');
step('a',13,30,0,now);now+=10000;step('a',30,31,1,now);assert.equal(count(),10,'Jump resets timer');
now+=10000;step('b',0,1,1,now);assert.equal(count(),10,'Switching schemes resets timer');
context.document.hidden=true;now+=10000;step('b',1,2,1,now);assert.equal(count(),10,'Background excluded');
context.document.hidden=false;events.visibilitychange();now+=10000;step('b',2,3,1,now);assert.equal(count(),10);
now+=10000;step('b',3,4,1,now);assert.equal(count(),11);
step('b',4,3,-1,now);assert.equal(count(),10,'Undo removes measured cell');
events.blur();now+=10000;step('b',3,4,1,now);assert.equal(count(),10,'Unfocused time excluded');
assert.equal(context.knittingPace(now+29*86400000),null,'Stale samples excluded');
assert.equal(context.knittingDuration(1,360),'5 мин','Estimates rounded rather than false precision');
console.log('PASS: pace, estimates, pause, double tap, jump, switch, visibility, undo and expiry');
