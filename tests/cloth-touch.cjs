const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'../index.html'),'utf8');
let reduced=false,queue=[],frames=[],time=0;
const context={matchMedia:()=>({matches:!reduced}),requestAnimationFrame:fn=>queue.push(fn),bendClothPreview:(_,x,y)=>frames.push([x,y])};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function attachClothHover('),source.indexOf('let albumActiveId')),context);
const cv={getBoundingClientRect:()=>({left:0,right:200,top:0,width:200,height:240})};
const button={isConnected:true,getBoundingClientRect:()=>({top:0,height:300}),querySelector:()=>({getBoundingClientRect:()=>({top:160})})};
context.attachClothHover(button,cv);
const settle=()=>{let count=0;while(queue.length){assert.ok(count++<200);queue.shift()(time+=17);}};
const touch={pointerType:'touch',buttons:1,clientX:175,clientY:40};
button.onpointerdown(touch);settle();assert.ok(frames.at(-1)[0]>.5,'Touch bends exposed cloth');
button.onpointercancel();settle();assert.deepEqual(frames.at(-1),[0,0],'Scrolling cancellation releases cloth');
button.onpointermove({...touch,buttons:0});assert.equal(queue.length,0,'Released touch cannot bend cloth');
button.onpointerdown(touch);settle();button.onpointerup();settle();assert.deepEqual(frames.at(-1),[0,0]);
reduced=true;button.onpointerdown(touch);assert.equal(queue.length,0,'Reduced motion ignores touch');
reduced=false;button.onpointermove({...touch,pointerType:'mouse',buttons:0});settle();assert.ok(frames.at(-1)[0]>.5,'Mouse hover preserved');
button.onpointerleave();settle();assert.deepEqual(frames.at(-1),[0,0]);
console.log('PASS: touch, release, scroll cancellation, reduced motion and mouse hover');
