'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
function list(dir) {
  return fs.readdirSync(path.join(root, dir), {withFileTypes: true}).flatMap(entry => {
    const name = `${dir}/${entry.name}`;
    return entry.isDirectory() ? list(name) : [name];
  });
}
const assets = ['index.html', 'manifest.webmanifest',
  ...list('styles').filter(name => name.endsWith('.css')),
  ...list('scripts').filter(name => name.endsWith('.js')),
  ...list('assets').filter(name => /\.(png|svg|ttf|woff2?)$/.test(name))].sort();
const hash = crypto.createHash('sha256');
for (const name of [...assets, 'sw.js']) {
  hash.update(name + '\0');
  hash.update(fs.readFileSync(path.join(root, name)));
}
const config = {version: hash.digest('hex').slice(0, 16), assets};
const output = '// Generated by node scripts/build-offline.cjs.\nself.FILET_OFFLINE = ' + JSON.stringify(config, null, 2) + ';\n';
const target = path.join(root, 'offline-assets.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
    console.error('Offline files changed. Run node scripts/build-offline.cjs before publishing.');
    process.exitCode = 1;
  } else console.log('Offline release is up to date.');
} else {
  fs.writeFileSync(target, output);
  console.log(`Prepared ${assets.length} offline files (${config.version}).`);
}
